-- Supabase SQL Schema for TripMates Tamil Nadu

-- 1. PROFILES TABLE (Linked with Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  full_name TEXT,
  avatar_url TEXT,
  location TEXT,
  bio TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. DESTINATIONS TABLE
CREATE TABLE IF NOT EXISTS public.destinations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  image_url TEXT NOT NULL,
  rating NUMERIC(3,2) DEFAULT 4.9,
  travelers_count INT DEFAULT 1000,
  price TEXT NOT NULL,
  duration TEXT NOT NULL,
  description TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. SAVED DESTINATIONS (User Favorites)
CREATE TABLE IF NOT EXISTS public.saved_destinations (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  destination_id BIGINT REFERENCES public.destinations(id) ON DELETE CASCADE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(user_id, destination_id)
);

-- 4. TRAVEL PLANS TABLE
CREATE TABLE IF NOT EXISTS public.travel_plans (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  destination_name TEXT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  group_size INT DEFAULT 2,
  budget TEXT,
  notes TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. COMMUNITY POSTS (Testimonials & Stories)
CREATE TABLE IF NOT EXISTS public.community_posts (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
  author_name TEXT NOT NULL,
  author_location TEXT,
  author_avatar TEXT,
  rating INT DEFAULT 5,
  content TEXT NOT NULL,
  trip_name TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- RLS POLICIES (Row Level Security)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.destinations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_destinations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.travel_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_posts ENABLE ROW LEVEL SECURITY;

-- Allow public read access to destinations and community posts
CREATE POLICY "Public destinations viewable" ON public.destinations FOR SELECT USING (true);
CREATE POLICY "Public community posts viewable" ON public.community_posts FOR SELECT USING (true);

-- Allow authenticated users to manage their own profiles
CREATE POLICY "Users can view own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can update own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Users can insert own profile" ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);

-- Allow authenticated users to manage saved destinations
CREATE POLICY "Users can view own saved destinations" ON public.saved_destinations FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users can insert own saved destinations" ON public.saved_destinations FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can delete own saved destinations" ON public.saved_destinations FOR DELETE USING (auth.uid() = user_id);

-- Allow authenticated users to manage travel plans
CREATE POLICY "Users can view own travel plans" ON public.travel_plans FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users can insert own travel plans" ON public.travel_plans FOR INSERT WITH CHECK (auth.uid() = user_id);

